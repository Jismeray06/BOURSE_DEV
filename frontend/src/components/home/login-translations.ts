const normalizedMessages = Object.fromEntries(
  (Object.keys(serverMessages) as Exclude<Language, 'fr'>[]).map((language) => [
    language,
    Object.fromEntries(Object.entries(serverMessages[language]).map(([french, translated]) => [normalize(french), translated])),
  ]),
) as Record<Exclude<Language, 'fr'>, Dictionary>;

export function translateServerMessage(message: string, language: Language): string {
  if (language === 'fr' || !message) return message;
  return normalizedMessages[language][normalize(message)] ?? message;
}
