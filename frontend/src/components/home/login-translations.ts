export function loginT(key: string, language: Language, values: Record<string, string | number> = {}): string {
  const text = loginText[language][key] ?? loginText.fr[key] ?? key;
  return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), text);
}

